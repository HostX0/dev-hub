// Downloads the OFL-licensed Google Fonts used by the site and the template demos into
// src/app/fonts/demos and writes src/demos/fonts.local.ts (next/font/local declarations).
// Self-hosting keeps `next build` independent of fonts.gstatic.com, which is flaky from
// some networks and would otherwise break Docker builds.
//
//   node scripts/fetch-demo-fonts.mjs
//
// The legacy-UA request returns one .woff per weight containing all requested subsets
// (no unicode-range splitting), which is what next/font/local needs.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(here, "../src/app/fonts/demos");
const TS = join(here, "../src/demos/fonts.local.ts");
mkdirSync(OUT, { recursive: true });

const UA = "Mozilla/5.0 (Windows NT 6.1; rv:27.0) Gecko/20100101 Firefox/27.0";
const FAMILIES = [
  { key: "plex", family: "IBM Plex Sans Arabic", weights: ["400", "500", "600", "700"], subsets: "arabic,latin" },
  { key: "playfair", family: "Playfair Display", weights: ["400", "700"], subsets: "latin" },
  { key: "amiri", family: "Amiri", weights: ["400", "700"], subsets: "arabic,latin" },
  { key: "cormorant", family: "Cormorant", weights: ["400", "500", "600", "400italic"], subsets: "latin" },
  { key: "reem", family: "Reem Kufi", weights: ["400", "600"], subsets: "arabic,latin" },
  { key: "fraunces", family: "Fraunces", weights: ["400", "700"], subsets: "latin" },
  { key: "lalezar", family: "Lalezar", weights: ["400"], subsets: "arabic,latin" },
  { key: "rubik", family: "Rubik", weights: ["400", "500", "700"], subsets: "arabic,latin" },
  { key: "cairo", family: "Cairo", weights: ["400", "600", "700", "800"], subsets: "arabic,latin" },
  { key: "manrope", family: "Manrope", weights: ["400", "600", "700", "800"], subsets: "latin" },
  { key: "inter", family: "Inter", weights: ["400", "500", "600", "700", "800"], subsets: "latin" },
  { key: "tajawal", family: "Tajawal", weights: ["400", "500", "700", "800"], subsets: "arabic,latin" },
  { key: "notoArabic", family: "Noto Sans Arabic", weights: ["400", "500", "700"], subsets: "arabic" },
];

async function fetchText(url) {
  const res = await fetch(url, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return res.text();
}

const decls = [];
for (const f of FAMILIES) {
  const url = `https://fonts.googleapis.com/css?family=${encodeURIComponent(f.family)}:${f.weights.join(",")}&subset=${f.subsets}&display=swap`;
  const css = await fetchText(url);
  const faces = [...css.matchAll(/font-style:\s*(\w+);\s*font-weight:\s*(\d+);[^}]*?url\(([^)]+\.woff)\)/g)];
  if (!faces.length) throw new Error(`No faces parsed for ${f.family}`);
  const src = [];
  for (const [, style, weight, fileUrl] of faces) {
    const name = `${f.key}-${weight}${style === "italic" ? "-italic" : ""}.woff`;
    const buf = Buffer.from(await (await fetch(fileUrl, { headers: { "User-Agent": UA } })).arrayBuffer());
    writeFileSync(join(OUT, name), buf);
    src.push({ path: `../app/fonts/demos/${name}`, weight, style });
    console.log("saved", name, `${(buf.length / 1024).toFixed(0)} KB`);
  }
  decls.push(
    `export const ${f.key} = localFont({\n  variable: "--font-${f.key.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase())}",\n  display: "swap",\n  preload: false,\n  src: [\n${src
      .map((s) => `    { path: "${s.path}", weight: "${s.weight}", style: "${s.style}" },`)
      .join("\n")}\n  ],\n});`,
  );
}

writeFileSync(
  TS,
  `// Generated by scripts/fetch-demo-fonts.mjs — do not edit by hand.\n// Self-hosted, OFL-licensed Google Fonts for the template demos (see src/app/fonts/demos/LICENSE.md).\nimport localFont from "next/font/local";\n\n${decls.join("\n\n")}\n`,
);
writeFileSync(
  join(OUT, "LICENSE.md"),
  `# Demo fonts\n\nAll families in this folder are distributed under the SIL Open Font License 1.1 and were downloaded from Google Fonts by \`scripts/fetch-demo-fonts.mjs\`:\n\n${FAMILIES.map((f) => `- ${f.family} — https://fonts.google.com/specimen/${encodeURIComponent(f.family.replace(/ /g, "+"))}`).join("\n")}\n`,
);
console.log("wrote", TS);
